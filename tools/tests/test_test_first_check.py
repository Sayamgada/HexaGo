import pytest

import test_first_check as tfc
from conftest import commit_all, git


@pytest.mark.parametrize("path, reason", [
    ("apps/hexago_app/lib/x.dart", "not a services/ source file"),
    ("services/dispatch-go/README.md", "not a services/ source file"),
    ("services/dispatch-go/internal/geo/geo_test.go", "test file"),
    ("services/agents-py/tests/helpers.py", "test file"),
    ("services/dispatch-go/internal/store/migrations/0002.go", "migration"),
    ("services/agents-py/alembic/versions/abc.py", "migration"),
    ("services/dispatch-go/cmd/tool/run.go", "entrypoint"),
    ("services/agents-py/src/agents_py/__init__.py", "entrypoint"),
    ("services/agents-py/src/agents_py/main.py", "entrypoint"),
    ("services/dispatch-go/internal/api/api.pb.go", "generated"),
    ("services/agents-py/src/agents_py/api_pb2.py", "generated"),
    ("services/dispatch-go/internal/x/zz_generated_deepcopy.go", "generated"),
])
def test_skip_reasons(path, reason):
    assert tfc.skip_reason(path) == reason


def test_generated_header_detected():
    read = lambda p: "// Code generated by stringer; DO NOT EDIT.\npackage x\n"  # noqa: E731
    assert tfc.skip_reason("services/dispatch-go/internal/x/kind_string.go", read) == "generated"

    def boom(p):
        raise OSError
    assert tfc.skip_reason("services/dispatch-go/internal/x/real.go", boom) is None
    assert tfc.skip_reason("services/dispatch-go/internal/x/real.go", lambda p: "package x") is None


def test_go_matching_rules():
    all_files = {"services/dispatch-go/internal/geo/geo.go",
                 "services/dispatch-go/internal/geo/geo_test.go",
                 "services/dispatch-go/internal/ledger/ledger.go",
                 "services/dispatch-go/internal/pricing/pricing.go"}
    added = ["services/dispatch-go/internal/geo/geo.go",          # existing geo_test.go
             "services/dispatch-go/internal/ledger/ledger.go",    # nothing
             "services/dispatch-go/internal/pricing/pricing.go",  # any new test in dir
             "services/dispatch-go/internal/pricing/surge_test.go"]
    missing, checked = tfc.check(added, all_files | set(added))
    assert missing == ["services/dispatch-go/internal/ledger/ledger.go"]
    assert len(checked) == 3


def test_python_matching_rules():
    all_files = {"services/agents-py/src/agents_py/core/llm.py",
                 "services/agents-py/tests/core/test_llm.py",
                 "services/agents-py/src/agents_py/core/ledger.py",
                 "services/agents-py/src/agents_py/cors.py",
                 "services/other/tests/test_cors.py"}
    missing, _ = tfc.check(["services/agents-py/src/agents_py/core/llm.py",
                            "services/agents-py/src/agents_py/core/ledger.py",
                            "services/agents-py/src/agents_py/cors.py"], all_files)
    assert missing == ["services/agents-py/src/agents_py/core/ledger.py",
                       "services/agents-py/src/agents_py/cors.py"]  # other service's test doesn't count


def _w(repo, rel, text="x\n"):
    p = repo / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="")


def test_main_against_git(repo, monkeypatch, tmp_path):
    _w(repo, "README.md")
    base = commit_all(repo)
    _w(repo, "services/dispatch-go/internal/ledger/ledger.go", "package ledger\n")
    _w(repo, "services/dispatch-go/cmd/server/main.go", "package main\n")
    commit_all(repo, "add ledger")
    monkeypatch.setattr(tfc, "REPO_ROOT", repo)
    summary = tmp_path / "summary.md"
    monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(summary))
    assert tfc.main(["--base", base]) == 1
    assert "❌ no test for `services/dispatch-go/internal/ledger/ledger.go`" in summary.read_text(encoding="utf-8")

    _w(repo, "services/dispatch-go/internal/ledger/ledger_test.go", "package ledger\n")
    commit_all(repo, "add test")
    assert tfc.main(["--base", base]) == 0
    assert tfc.main(["--base", git(repo, "rev-parse", "HEAD")]) == 0  # nothing new
