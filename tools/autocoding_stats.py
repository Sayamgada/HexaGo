#!/usr/bin/env python3
"""Compute HexaGo's autocoding statistics and write docs/AUTOCODING_STATS.md.

- total commits (excluding the bot's own stats commits)
- share of commits logged in docs/AUTOCODING_LOG.md (commits that add to it)
- number of entries in the log table
- ai-autofix PRs (opened / merged) and ai-autofix-failed PRs, via `gh api`
- current core coverage, from the coverage gate's JSON summary

Usage: python tools/autocoding_stats.py [--coverage-json coverage-summary.json]
                                        [--out docs/AUTOCODING_STATS.md]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

REPO_ROOT = Path(__file__).resolve().parent.parent
LOG_PATH = "docs/AUTOCODING_LOG.md"
STATS_SUBJECT = "chore(stats):"
LOG_ROW_RE = re.compile(r"^\|\s*\d+\s*\|", re.M)

Runner = Callable[..., subprocess.CompletedProcess]


@dataclass
class Stats:
    head: str
    total_commits: int
    logged_commits: int
    log_entries: int
    autofix_prs: int | None
    autofix_merged: int | None
    autofix_failed_prs: int | None
    coverage: dict | None

    @property
    def logged_share(self) -> float:
        return 0.0 if not self.total_commits else 100.0 * self.logged_commits / self.total_commits


def _run(args: list[str], run: Runner, cwd: Path = REPO_ROOT) -> str:
    res = run(args, cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"{' '.join(args)}: {res.stderr.strip()}")
    return res.stdout


def commit_counts(run: Runner = subprocess.run, root: Path = REPO_ROOT) -> tuple[int, int]:
    """(total, logged) commits on HEAD, excluding stats-bot commits."""
    all_commits = _run(["git", "log", "--format=%H%x09%s"], run, root).splitlines()
    real = {h for h, _, s in (ln.partition("\t") for ln in all_commits if ln)
            if not s.startswith(STATS_SUBJECT)}
    logged = set(_run(["git", "log", "--format=%H", "--", LOG_PATH], run, root).split())
    return len(real), len(real & logged)


def count_log_entries(text: str) -> int:
    return len(LOG_ROW_RE.findall(text))


def origin_repo(run: Runner = subprocess.run, root: Path = REPO_ROOT) -> str:
    """owner/name parsed from the origin remote URL ('' if none)."""
    try:
        url = _run(["git", "remote", "get-url", "origin"], run, root).strip()
    except RuntimeError:
        return ""
    m = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?/?$", url)
    return m.group(1) if m else ""


def search_count(query: str, run: Runner = subprocess.run) -> int | None:
    """Issue-search total via `gh api`; None if gh is unavailable or unscoped."""
    try:
        out = _run(["gh", "api", "-X", "GET", "search/issues", "-f", f"q={query}",
                    "-f", "per_page=1", "--jq", ".total_count"], run)
        return int(out.strip())
    except (RuntimeError, ValueError, FileNotFoundError):
        return None


def collect(coverage_json: Path | None, run: Runner = subprocess.run,
            root: Path = REPO_ROOT, repo: str | None = None) -> Stats:
    total, logged = commit_counts(run, root)
    head = _run(["git", "rev-parse", "--short", "HEAD"], run, root).strip()
    log_file = root / LOG_PATH
    entries = count_log_entries(log_file.read_text(encoding="utf-8")) if log_file.exists() else 0
    repo = repo or os.environ.get("GITHUB_REPOSITORY") or origin_repo(run, root)
    cov = None
    if coverage_json and coverage_json.exists():
        cov = json.loads(coverage_json.read_text(encoding="utf-8"))

    def prs(query: str) -> int | None:  # never search all of GitHub
        return search_count(f"repo:{repo} is:pr {query}", run) if repo else None

    return Stats(
        head=head, total_commits=total, logged_commits=logged, log_entries=entries,
        autofix_prs=prs("label:ai-autofix"),
        autofix_merged=prs("is:merged label:ai-autofix"),
        autofix_failed_prs=prs("label:ai-autofix-failed"),
        coverage=cov,
    )


def _n(v: int | None) -> str:
    return "n/a" if v is None else str(v)


def render(s: Stats) -> str:
    lines = [
        "# Autocoding Stats",
        "",
        f"_Generated by `tools/autocoding_stats.py` in CI on `main` at `{s.head}`. "
        "Do not edit by hand._",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Total commits (excluding stats commits) | {s.total_commits} |",
        f"| Commits logged in [AUTOCODING_LOG.md](AUTOCODING_LOG.md) | "
        f"{s.logged_commits} ({s.logged_share:.1f}%) |",
        f"| Entries in the autocoding log | {s.log_entries} |",
        f"| `ai-autofix` PRs opened | {_n(s.autofix_prs)} |",
        f"| `ai-autofix` PRs merged | {_n(s.autofix_merged)} |",
        f"| `ai-autofix-failed` PRs | {_n(s.autofix_failed_prs)} |",
    ]
    cov = s.coverage
    if cov:
        overall = cov.get("overall_percent")
        lines.append(f"| Core coverage (gate ≥ {cov.get('threshold', 96):g}%) | "
                     f"{'n/a' if overall is None else f'{overall:.2f}%'} |")
        lines += ["", "## Core coverage by package", "",
                  "| Language | Package | Coverage | Status |", "|---|---|---:|---|"]
        for p in cov.get("packages", []):
            pct = "—" if p.get("percent") is None else f"{p['percent']:.2f}%"
            lines.append(f"| {p['language']} | `{p['package']}` | {pct} | {p['status']} |")
    else:
        lines.append("| Core coverage | n/a |")
    lines += ["", "How these are produced: see [AUTOCODING.md](AUTOCODING.md)."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write docs/AUTOCODING_STATS.md")
    ap.add_argument("--coverage-json", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "AUTOCODING_STATS.md")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):  # emoji on Windows consoles
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    md = render(collect(args.coverage_json))
    args.out.write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
